"""Third-party licences: check that every runtime dependency is compatible with the AGPL-3.0, and write
THIRD_PARTY_LICENSES.md.

    uv sync --frozen --no-dev
    .venv/bin/python scripts/licenses.py            # check only (CI)
    .venv/bin/python scripts/licenses.py --write    # also regenerate THIRD_PARTY_LICENSES.md

Run it with the Python of the environment to check: it reads each installed package's own metadata (the PEP 639
``License-Expression``, else the ``License`` field, else the licence classifiers). Only runtime dependencies count
(the ones in the Docker image); development tools are not distributed.
"""

from __future__ import annotations

import re
import subprocess
import sys
from importlib import metadata
from pathlib import Path

# Licences that can be combined with AGPL-3.0 code (permissive ones, the LGPL, the MPL-2.0, the GPL-3.0 family).
COMPATIBLE = re.compile(
    r"\b(MIT|BSD|0BSD|Apache|ISC|PSF|Python Software Foundation|MPL[- ]?2|Mozilla Public License 2|LGPL|"
    r"Lesser General Public|GPL[- ]?v?3|GNU General Public License v3|AGPL|Unlicense|CC0|Zlib|HPND|"
    r"Historical Permission Notice)",
    re.IGNORECASE,
)
# GPL-2.0-only cannot be combined with GPL-3.0/AGPL-3.0 code; these must never pass even if a pattern above matches.
INCOMPATIBLE = re.compile(r"GPL[- ]?v?2(\.0)?[- ]?only|SSPL|Commons Clause|Business Source|proprietary", re.IGNORECASE)
VENDORED_JS = [
    ("Alpine.js (CSP build)", "3.17.5", "MIT", "https://github.com/alpinejs/alpine"),
    ("htmx", "2.0.11", "0BSD", "https://github.com/bigskysoftware/htmx"),
    ("@zxing/library", "0.23", "Apache-2.0", "https://github.com/zxing-js/library"),
    ("@zxing/browser", "0.2.1", "MIT", "https://github.com/zxing-js/browser"),
]
FONT_ROW = (
    "| Plus Jakarta Sans | SIL Open Font License 1.1 | `mealtally/static/fonts/` (licence alongside); outlined in the"
    " wordmark | https://github.com/tokotype/PlusJakartaSans |"
)


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def runtime_packages() -> set[str]:
    out = subprocess.run(
        ["uv", "export", "--frozen", "--no-dev", "--no-hashes", "--no-emit-project"],  # noqa: S607
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return {
        norm(re.split(r"[=<>; \[]", line, maxsplit=1)[0])
        for line in out.splitlines()
        if line and not line.startswith(("#", " ", "-"))
    }


def licence_of(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    if meta.get("License-Expression"):
        return meta["License-Expression"]
    text = (meta.get("License") or "").strip()
    # a short, recognisable licence name wins; long pasted texts and vague values ("Dual License") use the classifiers
    if text and len(text) < 80 and "\n" not in text and COMPATIBLE.search(text):  # noqa: PLR2004
        return text
    classifiers = [c.split(" :: ")[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return "; ".join(classifiers)
    return text.splitlines()[0] if text else "UNKNOWN"


def source_of(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    if meta.get("Home-page"):
        return meta["Home-page"]
    for url in meta.get_all("Project-URL") or []:
        label, _, link = url.partition(",")
        if label.strip().lower() in ("source", "source code", "repository", "homepage", "home", "github"):
            return link.strip()
    return ""


def main() -> int:
    wanted = runtime_packages()
    installed = {norm(d.metadata["Name"]): d for d in metadata.distributions()}
    rows, problems, absent = [], [], []
    for name in sorted(wanted):
        dist = installed.get(name)
        if dist is None:  # a dependency for another platform (Windows, PyPy): not in this environment, nor the image
            absent.append(name)
            continue
        licence = licence_of(dist)
        rows.append((dist.metadata["Name"], dist.version, licence, source_of(dist)))
        if INCOMPATIBLE.search(licence) or not COMPATIBLE.search(licence):
            problems.append(f"{dist.metadata['Name']} {dist.version}: {licence}")
    for line in problems:
        print("licence problem:", line)
    if absent:
        print("not installed here (other platforms only):", ", ".join(absent))
    print(f"{len(rows)} runtime packages checked, {len(problems)} problem(s)")
    if "--write" in sys.argv:
        lines = [
            "# Third-party licences",
            "",
            "Mealtally is licensed under the AGPL-3.0-only. It includes or depends on the following third-party",
            "software, each under its own licence. Generated by `scripts/licenses.py`; don't edit by hand.",
            "",
            "## JavaScript shipped in `mealtally/static/vendor/`",
            "",
            "| Package | Version | Licence | Source |",
            "|---|---|---|---|",
            *[f"| {n} | {v} | {lic} | {url} |" for n, v, lic, url in VENDORED_JS],
            "",
            "## Python packages in the container image",
            "",
            "| Package | Version | Licence | Source |",
            "|---|---|---|---|",
            *[f"| {n} | {v} | {lic} | {url} |" for n, v, lic, url in rows],
            "",
            "## Fonts",
            "",
            "| Font | Licence | Where | Source |",
            "|---|---|---|---|",
            FONT_ROW,
            "",
            "## Logo and icons",
            "",
            "The Mealtally logo and icons in `assets/brand/` belong to the project and are not covered by the code",
            "licence; see TRADEMARK.md.",
            "",
        ]
        Path("THIRD_PARTY_LICENSES.md").write_text("\n".join(lines), encoding="utf-8")
        print("wrote THIRD_PARTY_LICENSES.md")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
