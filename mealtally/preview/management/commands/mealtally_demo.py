"""``make demo``: create (or refresh) two demo restaurants and print a fresh set of logins.

Development only: refuses to run unless ``MEALTALLY_ENV=development`` or ``DEBUG`` is on. Every run gives every demo
staff member a new random password and every demo customer a new PIN, so the printed list always works and no password
is ever fixed in the code. ``make demo`` writes the output to ``./.demo-credentials`` (mode 600, gitignored).

The restaurants hold real pass data written through the normal services, and their Preview modules (wallet, orders,
kitchen, delivery, ...) are switched on and labelled "Preview".
"""

from __future__ import annotations

import io
import tempfile
from pathlib import Path

from django.conf import settings
from django.core.management import call_command
from django.core.management.base import BaseCommand
from django.core.management.base import CommandError
from django.db import transaction

from mealtally.accounts import services as accounts
from mealtally.accounts.models import Role
from mealtally.accounts.models import User
from mealtally.accounts.policy import Actor
from mealtally.customers import services as customers
from mealtally.customers.models import Customer
from mealtally.tenancy.context import platform_context
from mealtally.tenancy.context import tenant_context
from mealtally.tenancy.models import Tenant

DEMOS = (
    # slug, name, staff email domain, theme
    ("demo-tiffin", "Saffron Tiffins & Mess (Demo)", "saffrontiffins.example.com", "masala"),
    ("demo-fresh", "Leafline Bowls (Demo)", "leaflinebowls.example.com", "fresh"),
)
ADMIN_EMAIL = "admin@example.com"


def demo_allowed() -> bool:
    return bool(settings.DEBUG) or settings.MEALTALLY_ENV == "development"


class Command(BaseCommand):
    help = "Development only: create or refresh two demo restaurants and print fresh logins (used by `make demo`)."

    def handle(self, *args, **opts):
        if not demo_allowed():
            raise CommandError(
                "make demo only runs in development (MEALTALLY_ENV=development or DEBUG=true). "
                "It creates restaurants full of sample data and must never run on a real instance."
            )
        base = settings.MEALTALLY_BASE_URL.rstrip("/")
        lines = [
            "# Mealtally demo logins. Development only; regenerated by every `make demo`.",
            f"# Sign in at {base}/login (staff and admins) or on each restaurant's page (customers).",
            "",
        ]
        admin, password = self._admin()
        if password:
            lines += [f"PLATFORM ADMIN  login={admin.email}  password={password}", ""]
        else:
            lines += [f"PLATFORM ADMIN  {admin.email}: the account you created with `make init`", ""]
        for slug, name, domain, theme in DEMOS:
            lines += [f"## {name}  {base}/t/{slug}/", *self._restaurant(admin, slug, name, domain, theme), ""]
        self.stdout.write("\n".join(lines))

    # ------------------------------------------------------------------------------------------------------------
    def _admin(self) -> tuple[User, str]:
        """The first platform admin, or a new demo one (whose generated password is returned once)."""
        with platform_context():
            admin = User.objects.filter(is_platform_admin=True, is_active=True).order_by("pk").first()
            if admin is not None:
                return admin, ""
            password = accounts.temp_password()
            admin = User.objects.create_user(email=ADMIN_EMAIL, password=password, name="Demo admin")
            User.objects.filter(pk=admin.pk).update(is_platform_admin=True, is_staff=True, must_change_password=False)
            admin.refresh_from_db()
            return admin, password

    def _restaurant(self, admin: User, slug: str, name: str, domain: str, theme: str) -> list[str]:
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "logins.txt"
            call_command(
                "seed_demo_tiffin",
                slug=slug,
                name=name,
                domain=domain,
                theme=theme,
                platform_admin=admin.email,
                credentials_file=str(out),
                stdout=io.StringIO(),
            )
        with platform_context():
            tenant = Tenant.objects.get(slug=slug)
            # demo restaurants are ordinary restaurants on a development instance: listed, with Preview modules on
            Tenant.objects.filter(pk=tenant.pk).update(is_test=False, has_demo_dataset=True, show_preview_badges=True)
        return self._fresh_logins(admin, tenant)

    def _fresh_logins(self, admin: User, tenant: Tenant) -> list[str]:
        """New random password for every staff member, new PIN for every customer; no forced change (it's a demo)."""
        actor = Actor(user=admin, role=Role.OWNER, tenant_id=tenant.id)
        staff, people = [], []
        with tenant_context(tenant.id), transaction.atomic():
            for m in accounts.list_staff(tenant.id).filter(is_active=True).order_by("role", "user__email"):
                user, password = accounts.reset_staff_password(actor=actor, user_id=m.user_id)
                User.objects.filter(pk=user.pk).update(must_change_password=False)
                staff.append(f"{m.get_role_display():<9} login={user.get_username()}  password={password}")
            for customer in Customer.objects.filter(status=Customer.Status.ACTIVE).order_by("customer_code")[:8]:
                pin = customers.reset_pin(actor=actor, customer=customer)
                Customer.objects.filter(pk=customer.pk).update(must_change_pin=False)
                people.append(f"CUSTOMER  {customer.full_name:<20} phone={customer.phone_e164}  pin={pin}")
        return [*staff, *people]
